const LangCtx = createContext<{ lang: Lang; setLang: (l: Lang) => void }>({
  lang: "zh",
  setLang: () => {},
});

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>(() => {
    try {
      const stored = typeof localStorage === "undefined" ? null : localStorage.getItem("jevloop.lang");
      return (stored as Lang) || "zh";
    } catch {
      return "zh";
    }
  });
  useEffect(() => {
    localStorage.setItem("jevloop.lang", lang);
    document.documentElement.lang = lang === "zh" ? "zh-CN" : "en";
  }, [lang]);
  return <LangCtx.Provider value={{ lang, setLang }}>{children}</LangCtx.Provider>;
}

export function useLang() {
  return useContext(LangCtx);
}

/** t("key") or t("key", {a: 1, b: 2}) for {a}/{b} substitution. */
export function useT() {
  const { lang } = useLang();
  return (key: string, vars?: Record<string, string | number | null>) => {
    let text = dict[lang][key] ?? dict.en[key] ?? key;
    if (vars) {
      for (const [k, v] of Object.entries(vars)) {
        text = text.replaceAll(`{${k}}`, String(v ?? "–"));
      }
    }
    return text;
  };
}

export function LangToggle() {
  const { lang, setLang } = useLang();
  return (
    <div className="ml-auto flex overflow-hidden rounded-xl border border-line text-xs font-semibold">
      {(["zh", "en"] as Lang[]).map((option) => (
        <button
          key={option}
          onClick={() => setLang(option)}
          className={`px-2.5 py-1 ${lang === option ? "bg-accent text-white" : "text-ink2 hover:text-ink"}`}
        >
          {option === "zh" ? "中文" : "EN"}
        </button>
      ))}
    </div>
  );
}
